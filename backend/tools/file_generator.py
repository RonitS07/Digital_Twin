MIME_MAP = {
    "pdf": "application/pdf",
    "docx": "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
    "xlsx": "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
    "pptx": "application/vnd.openxmlformats-officedocument.presentationml.presentation",
    "txt": "text/plain",
    "md": "text/markdown",
    "csv": "text/csv",
    "json": "application/json",
    "yaml": "text/yaml",
    "yml": "text/yaml",
    "py": "text/x-python",
    "js": "text/javascript",
    "ts": "text/typescript",
    "html": "text/html",
    "css": "text/css",
    "sql": "text/x-sql",
    "sh": "text/x-shellscript",
}


def detect_file_type(user_input: str, ai_decision: str = None) -> str:
    """Detect best file type from user message or AI decision."""
    text = (ai_decision or user_input).lower()
    if any(w in text for w in ["pdf", "report", "invoice", "resume", "cv"]): return "pdf"
    if any(w in text for w in ["word", "docx", "document", "letter", "proposal"]): return "docx"
    if any(w in text for w in ["excel", "xlsx", "spreadsheet", "sheet", "expenses", "budget", "table"]): return "xlsx"
    if any(w in text for w in ["pptx", "powerpoint", "presentation", "slide", "deck"]): return "pptx"
    if any(w in text for w in ["csv", "comma separated"]): return "csv"
    if any(w in text for w in ["json", "config", "api response"]): return "json"
    if any(w in text for w in ["yaml", "yml", "kubernetes", "docker-compose", "configuration"]): return "yaml"
    if any(w in text for w in ["python script", "py file", ".py", "python code"]): return "py"
    if any(w in text for w in ["javascript", ".js file", "js script"]): return "js"
    if any(w in text for w in ["typescript", ".ts file"]): return "ts"
    if any(w in text for w in ["html", "webpage", "web page"]): return "html"
    if any(w in text for w in ["markdown", "readme", ".md"]): return "md"
    if any(w in text for w in ["sql", "query", "database script"]): return "sql"
    if any(w in text for w in ["shell", "bash", "script", ".sh"]): return "sh"
    return "txt"


def generate_file(file_type: str, title: str, content: str, structured_data: dict = None, metadata: dict = None) -> tuple:
    """
    Master file generator.
    Returns: (storage_path, filename, mime_type)
    """
    ext = file_type.lower().lstrip(".")
    mime = MIME_MAP.get(ext, "application/octet-stream")
    metadata = metadata or {}

    try:
        if ext == "pdf":
            path, fname = generate_pdf(title, content, metadata)
        elif ext == "docx":
            path, fname = generate_docx(title, content, metadata)
        elif ext == "xlsx":
            rows = structured_data.get("rows", []) if structured_data else []
            headers = structured_data.get("headers", None) if structured_data else None
            path, fname = generate_xlsx(title, rows, headers, metadata)
        elif ext == "csv":
            rows = structured_data.get("rows", []) if structured_data else []
            headers = structured_data.get("headers", None) if structured_data else None
            path, fname = generate_csv(title, rows, headers)
        elif ext == "pptx":
            slides = structured_data.get("slides", []) if structured_data else [{"title": title, "content": content}]
            path, fname = generate_pptx(title, slides)
        elif ext == "json":
            data = structured_data or {"title": title, "content": content, "generated_at": datetime.utcnow().isoformat()}
            path, fname = generate_json_file(title, data)
        else:
            # All text-based: txt, md, py, js, ts, html, css, sql, sh, yaml, yml
            path, fname = generate_text_file(title, content, ext)

        logger.info(f"[FileGen] Generated {ext}: {fname}")
        return path, fname, mime
    except Exception as e:
        logger.error(f"[FileGen] Failed to generate {ext}: {e}")
        raise
